export function resolveCurrentCycleRange(contractId: number): CycleRange {
    const current = MOCK_CONTRACT_CYCLES.find(
        (c) => c.cycle.contractId === contractId && c.cycle.status === "OPEN"
    );
    return current ? current.cycle.range : { from: "2026-07-21", to: "2026-08-20" };
}

export function getContractCycleProfileMock(
    contractId: number,
    range: CycleRange
): MockContractCycleProfileData | null {
    const found = MOCK_CONTRACT_CYCLES.find(
        (item) =>
            item.cycle.contractId === contractId &&
            item.cycle.range.from === range.from &&
            item.cycle.range.to === range.to
    );

    if (!found) {
        return null;
    }

    return {
        cycle: found.cycle,
        entries: found.entries,
    };
}
